-- EX 13: FUNÇÕES PARA CONSULTAS

    -- TEXTOS
        SELECT UPPER(NOME) AS NOME_CLIENTE, LOWER(EMAIL) AS EMAIL_CLIENTE
        FROM CLIENTE;

    -- CONCAT CONCATENAÇÃO DE VALORES
        SELECT CONCAT(NOME, '---', CIDADE) AS CIDADE_CLIENTES
        FROM CLIENTE;

    -- NÚMEROS
        SELECT NOME, PRECO, ROUND (PRECO * 0.90, 2) AS PRECO_DESCONTO
        FROM PRODUTO;

    -- DATAS
        SELECT ID_PEDIDO, DATA_PEDIDO, DATE (DATA_PEDIDO) AS DATAS, MONTH (DATA_PEDIDO) AS MÊS, YEAR (DATA_PEDIDO) AS ANO, DAY (DATA_PEDIDO) AS DIA, TIME (DATA_PEDIDO) AS HORÁRIO
        FROM PEDIDO;

    -- COALESCE - SUBSTITUIR A INFORMAÇÃO QUE DEIXAMOS EM NULL OU NÃO DEIXAMOS
        SELECT NOME, COALESCE (TELEFONE, 'NÃO INFORMADO') AS TELEFONE
        FROM CLIENTE;

-- EX 14: FUNÇÕES DE AGRUPAMENTO
    
    -- COUNT - CONTAR QUANTOS REGISTROS EXISTEM
    -- SUM - SOMA DE VALORES
    -- AVG - MÉDIA DE VALORES
    -- MIN - MENOR VALOR
    -- MAX - MAIOR VALOR

    -- CONTAR QUANTOS CLIENTES EXISTEM
        SELECT COUNT (*) AS TOTAL_CLIENTES
        FROM CLIENTE;

    -- CALCULAR MÉDIA DE PREÇO DOS PRODUTOS
        SELECT AVG (ROUND(PRECO, 2)) AS MÉDIA_PREÇOS
        FROM PRODUTO;

    -- RESUMO DE PREÇOS
        SELECT MIN (PRECO) AS MENOR_PRECO, MAX (PRECO) AS MAIOR_PRECO, AVG (PRECO) AS MEDIA_PRECO
        FROM PRODUTO;
    
    -- TOTAL DE VENDAS OU PEDIDOS REALIZADOS COM CRITÉRIO, NESSE CASO, 'ABERTO'.
        SELECT SUM (VALOR_TOTAL) AS FATURAMENTO_MENSAL
        FROM PEDIDO 
        WHERE STATUS_PEDIDO = 'ABERTO'

-- EX 15: GROUP BY - AGRUPAR DADOS

    SELECT CIDADE, COUNT (*) AS QUANTIDADE_CLIENTES
    FROM CLIENTE
    GROUP BY CIDADE;
    
    SELECT ID_CATEGORIA, COUNT (*) AS QUNATIDADE_PRODUTOS
    FROM PRODUTO
    GROUP BY ID_CATEGORIA;

-- EX 16: HAVING - FILTRO POR GRUPOS

    -- WHERE - FILTRA LINHAS ANTES DO GROUP BY
    -- HAVING - FILTRA LINHAS DEPOIS DO GROUP BY

    -- CIDADES COM PELO MENOS DOIS CLIENTES
        SELECT CIDADE, COUNT (*) AS QUANTIDADE_CLIENTES
        FROM CLIENTE
        GROUP BY CIDADE
        HAVING COUNT (*) >= 2;

