CREATE DATABASE IF NOT EXISTS biblioteca_som2;

USE biblioteca_som2;

CREATE TABLE IF NOT EXISTS USUARIO (
    ID_USUARIO INT PRIMARY KEY AUTO_INCREMENT,
    NOME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(120) NOT NULL UNIQUE,
    TELEFONE VARCHAR (20),
    ATIVO BOOLEAN DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS LIVRO (
    ID_LIVRO INT PRIMARY KEY AUTO_INCREMENT,
    TITULO VARCHAR(150) NOT NULL,
    AUTOR VARCHAR(120) NOT NULL,
    ISBN CHAR(13) NOT NULL UNIQUE,
    ANO_PUBLICACAO INT NOT NULL,
    QUANTIDADE_DISPONIVEL INT DEFAULT 0, CHECK (QUANTIDADE_DISPONIVEL>=0)
);

CREATE TABLE IF NOT EXISTS EMPRESTIMO (
    ID_EMPRESTIMO INT PRIMARY KEY AUTO_INCREMENT,
    DATA_EMPRESTIMO DATETIME DEFAULT CURRENT_TIMESTAMP,
    DATA_PREVISTA DATE NOT NULL,
    DATA_DEVOLUCAO DATE NOT NULL,
    STATUS_EMPRESTIMO VARCHAR(20) DEFAULT 'ABERTO' CHECK (STATUS_EMPRESTIMO IN ('ABERTO', 'ATRASADO', 'DEVOLVIDO')),
    ID_USUARIO INT NOT NULL,
    ID_LIVRO INT NOT NULL,
    CONSTRAINT FK_ID_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO),
    CONSTRAINT FK_ID_LIVRO FOREIGN KEY (ID_LIVRO) REFERENCES LIVRO (ID_LIVRO)
);

CREATE TABLE IF NOT EXISTS FORNECEDORES (
    ID_FORNECEDOR INT PRIMARY KEY AUTO_INCREMENT,
    NOME_FORNECEDOR VARCHAR (100) NOT NULL,
    CNPJ CHAR (14) NOT NULL UNIQUE,
    TELEFONE VARCHAR (20) NOT NULL,
    EMAIL VARCHAR (120) NOT NULL UNIQUE,
    ENDERECO VARCHAR (200) NOT NULL
);

CREATE TABLE IF NOT EXISTS PAGAMENTO (
    ID_PAGAMENTO INT PRIMARY KEY AUTO_INCREMENT,
    DATA_PAGAMENTO DATETIME DEFAULT CURRENT_TIMESTAMP,
    VALOR DECIMAL (10,2) NOT NULL CHECK (VALOR >= 0),
    FORMA_PAGAMENTO VARCHAR (50) NOT NULL DEFAULT 'DEBITO' CHECK (FORMA_PAGAMENTO IN ('DINHEIRO', 'DEBITO', 'CREDITO', 'PIX')),
    QUANTIDADE_LIVROS INT NOT NULL CHECK (QUANTIDADE_LIVROS >= 0)
);

