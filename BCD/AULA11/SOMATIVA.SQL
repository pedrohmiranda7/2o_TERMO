SELECT MAX(QUANTIDADE_DISPONIVEL) AS QUANTIDADE_MAXIMA FROM LIVRO;

SELECT E.ID_EMPRESTIMO, U.ID_USUARIO, L.ID_LIVRO, E.DATA_EMPRESTIMO, E.STATUS_EMPRESTIMO
FROM EMPRESTIMO AS E
INNER JOIN USUARIO AS U
ON U.ID_USUARIO = E.ID_USUARIO
INNER JOIN LIVRO AS L
ON L.ID_LIVRO = E.ID_LIVRO;

SELECT E.STATUS_EMPRESTIMO 
FROM EMPRESTIMO AS E
INNER JOIN USUARIO AS U
ON E.ID_USUARIO = U.ID_USUARIO
WHERE E.STATUS_EMPRESTIMO = 'ABERTO'

SELECT U.ID_USUARIO, COUNT(E.ID_EMPRESTIMO) AS QUANTIDADE_EMPRESTIMOS
FROM EMPRESTIMO AS E
INNER JOIN USUARIO AS U
ON E.ID_USUARIO = U.ID_USUARIO
WHERE E.STATUS_EMPRESTIMO = 'ABERTO'
GROUP BY U.ID_USUARIO
ORDER BY QUANTIDADE_EMPRESTIMOS DESC;

SELECT U.ID_USUARIO, COUNT(E.ID_EMPRESTIMO) AS QUANTIDADE_EMPRESTIMOS
FROM USUARIO AS U
LEFT JOIN EMPRESTIMO AS E
ON U.ID_USUARIO = E.ID_USUARIO
GROUP BY U.ID_USUARIO
ORDER BY QUANTIDADE_EMPRESTIMOS DESC;

